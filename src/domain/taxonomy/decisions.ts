/**
 * A decision is one thing a senior engineer would settle before (or while) building.
 * The Prompt X-Ray checks a prompt against every applicable decision.
 *
 * Authoring rules (docs/content-guide.md):
 * - `question` is plain words a non-technical builder understands.
 * - `risk` says what goes wrong if the AI decides silently. One sentence, no scare tactics.
 * - `promptLine` is an instruction the builder can paste. Square brackets mark choices to fill in.
 * - `addressedWhen` / `partialWhen` guide the classifier. They are part of the AI prompt,
 *   so editing them changes classification: bump TAXONOMY_VERSION.
 * - weight: 3 = foundational, 2 = important, 1 = good practice.
 * - critical: missing it can cause data loss, data exposure or money loss. Critical decisions
 *   always have weight 3 and cap the score when missing (see scoring.ts).
 */
export interface Decision {
  id: string;
  domain: DomainId;
  chapter: ChapterId;
  question: string;
  weight: 1 | 2 | 3;
  critical: boolean;
  /** Undefined means the decision always applies. */
  appliesWhen?: { all?: TraitId[]; any?: TraitId[] };
  risk: string;
  promptLine: string;
  addressedWhen: string;
  partialWhen: string;
  /** Decision Card that teaches this decision, when one exists. */
  cardSlug?: string;
}

